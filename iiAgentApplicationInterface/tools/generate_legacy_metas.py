"""Generate the embedded schema text from the checked-in official resources."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT/'src/LegacyMetas.cpp'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
parts = ['// Generated by tools/generate_legacy_metas.py; source: resources/standard-metas.\n',
         '#include "LegacyMetas.h"\n\nnamespace iiAgentApplicationInterface::detail {\n',
         'std::optional<std::string_view> legacy_meta(std::string_view uri) noexcept {\n']
for version in range(4):
    for infix, suffix in (('', 'schema'), ('-hyper', 'hyper-schema'), ('-links', 'links')):
        name = f'draft-{version:02}' + infix + '.json'
        text = (ROOT/'resources/standard-metas'/name).read_text()
        assert ')IIAGENT_SCHEMA"' not in text
        path = f'json-schema.org/draft-{version:02}/{suffix}'
        parts += [f'    if (uri == "http://{path}" || uri == "https://{path}")\n',
                  '        return R"IIAGENT_SCHEMA(', text, ')IIAGENT_SCHEMA";\n']
parts += ['    return std::nullopt;\n}\n} // namespace iiAgentApplicationInterface::detail\n']
content = ''.join(parts)
if args.check:
    if not OUTPUT.exists() or OUTPUT.read_text() != content:
        raise SystemExit('Embedded legacy meta-schemas are stale')
else:
    OUTPUT.write_text(content)
